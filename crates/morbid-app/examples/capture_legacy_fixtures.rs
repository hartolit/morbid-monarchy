//! Captures legacy saved-world fixtures with the baseline writer.
//!
//! The application's save path (`runtime::persistence::process_save_queue`) encodes each
//! evicted `CellChunk` with `bitcode::encode` and commits the batch through
//! `RedbChunkStorage::write_batch`. This program performs exactly those two calls on a fixed
//! set of chunks so that later readers can be tested against bytes the old writer produced.
//!
//! Usage: `cargo run --locked -p morbid-app --example capture_legacy_fixtures -- OUTPUT_DIR`
//!
//! `OUTPUT_DIR` must not exist yet. The program never opens `world_data/save.redb`.

use std::{
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
    process::ExitCode,
    sync::Arc,
};

use monarch_engine::prelude::*;
use redb::Database;
use spatial_lib::prelude::{
    math::ChunkKey,
    storage::{ChunkStorage, redb_backend::RedbChunkStorage},
};

/// Seed hard-coded by `morbid_app::run` for every world in the baseline.
const BASELINE_SEED: u32 = 69;

struct FixtureRow {
    key: ChunkKey,
    description: &'static str,
    chunk: CellChunk,
}

fn main() -> ExitCode {
    let Some(output) = std::env::args_os().nth(1).map(PathBuf::from) else {
        eprintln!("usage: capture_legacy_fixtures OUTPUT_DIR");
        return ExitCode::FAILURE;
    };
    match capture(&output) {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("capture failed: {message}");
            ExitCode::FAILURE
        }
    }
}

fn capture(output: &Path) -> Result<(), String> {
    if output.exists() {
        return Err(format!(
            "{} already exists; refusing to overwrite",
            output.display()
        ));
    }
    let rows_dir = output.join("rows");
    fs::create_dir_all(&rows_dir).map_err(|e| format!("create {}: {e}", rows_dir.display()))?;

    let rows = fixture_rows();
    let encoded: Vec<(ChunkKey, Vec<u8>)> = rows
        .iter()
        .map(|row| (row.key, bitcode::encode(&row.chunk)))
        .collect();

    let db_path = output.join("legacy-chunks.redb");
    let database = Database::create(&db_path).map_err(|e| format!("create database: {e}"))?;
    let storage =
        RedbChunkStorage::new(Arc::new(database)).map_err(|e| format!("open storage: {e}"))?;
    // Two batches, as two periodic save flushes would commit them.
    let (first, second) = encoded.split_at(2);
    for batch in [first, second] {
        let refs: Vec<(ChunkKey, &[u8])> = batch
            .iter()
            .map(|(key, bytes)| (*key, bytes.as_slice()))
            .collect();
        storage
            .write_batch(&refs)
            .map_err(|e| format!("write batch: {e}"))?;
    }

    let mut manifest = String::from(
        "# Generated by crates/morbid-app/examples/capture_legacy_fixtures.rs.\n\
         # Cell sums and words were computed from the in-memory chunk before encoding.\n",
    );
    for (row, (key, bytes)) in rows.iter().zip(&encoded) {
        let file = row_file_name(*key);
        fs::write(rows_dir.join(&file), bytes).map_err(|e| format!("write {file}: {e}"))?;

        let read_back = storage
            .read_chunk(*key, |stored| stored.to_vec())
            .map_err(|e| format!("read back {file}: {e}"))?
            .ok_or_else(|| format!("{file} missing after commit"))?;
        if read_back != *bytes {
            return Err(format!("{file}: stored bytes differ from encoded bytes"));
        }
        let decoded: CellChunk =
            bitcode::decode(bytes).map_err(|e| format!("decode {file}: {e}"))?;
        if decoded != row.chunk {
            return Err(format!(
                "{file}: decoded chunk differs from the source chunk"
            ));
        }

        append_row(&mut manifest, row, &file, bytes.len());
    }
    fs::write(output.join("manifest.toml"), manifest).map_err(|e| format!("manifest: {e}"))?;
    Ok(())
}

fn fixture_rows() -> Vec<FixtureRow> {
    let generator = WorldGenerator::new(BASELINE_SEED);
    let generated = |x, y, z| generator.generate_chunk(ChunkKey::new(x, y, z));

    let mut edited = generated(2, 1, 0);
    edit_like_brushes(&mut edited);
    // `handle_chunk_loaded` stamps session-relative elapsed seconds on every loaded chunk.
    edited.metadata.last_simulated = 37.25;

    vec![
        FixtureRow {
            key: ChunkKey::new(0, 0, 0),
            description: "generated, seed 69, origin chunk",
            chunk: generated(0, 0, 0),
        },
        FixtureRow {
            key: ChunkKey::new(-1, -2, 0),
            description: "generated, seed 69, negative key components",
            chunk: generated(-1, -2, 0),
        },
        FixtureRow {
            key: ChunkKey::new(2, 1, 0),
            description: "generated, seed 69, then edited with the brush rules",
            chunk: edited,
        },
        FixtureRow {
            key: ChunkKey::new(7, -3, 0),
            description: "hand-built boundary chunk: field maxima, all-ones, mixed words",
            chunk: boundary_chunk(),
        },
        FixtureRow {
            key: ChunkKey::new(0, 0, 1),
            description: "synthetic: nonzero z, never written by the normal focus path",
            chunk: generated(0, 0, 1),
        },
    ]
}

/// Applies the same per-cell rules `handle_brush_input` uses for water, sand, raise terrain
/// and fire, without the window and ray.
fn edit_like_brushes(chunk: &mut CellChunk) {
    for (index, cell) in chunk.cells.iter_mut().enumerate() {
        let (x, y) = (index % CHUNK_SIZE, index / CHUNK_SIZE);
        if (10..20).contains(&x) && (10..20).contains(&y) {
            cell.inject_fluid(FluidMat::FLUID_WATER, 40);
        }
        if (30..36).contains(&x) && (30..36).contains(&y) {
            let current = if cell.granular_mat() == GranularMat::GRANULAR_SAND {
                cell.granular_vol()
            } else {
                0
            };
            cell.set_granular_mat(GranularMat::GRANULAR_SAND);
            cell.set_granular_vol(current + 12);
        }
        if (40..44).contains(&x) && (40..44).contains(&y) {
            let raised = cell
                .elevation()
                .saturating_add(25)
                .min(WorldCell::MAX_ELEVATION as u16);
            cell.set_elevation(raised);
        }
        if (50..52).contains(&x)
            && (50..52).contains(&y)
            && matches!(cell.fluid_mat(), FluidMat::EMPTY | FluidMat::FLUID_OIL)
        {
            cell.set_surface_mat(SurfaceMat::SURFACE_FIRE);
            cell.set_surface_state(0);
        }
    }
}

/// Words chosen so every packed field reaches zero and its maximum somewhere in the chunk.
fn boundary_chunk() -> CellChunk {
    let mut cells = vec![WorldCell::default(); CHUNK_CELL_COUNT];
    let field_maxima = [
        0x0000_0000_0000_000F, // terrain material
        0x0000_0000_0000_00F0, // surface material
        0x0000_0000_0000_0F00, // granular material
        0x0000_0000_0000_7000, // fluid material
        0x0000_0000_000F_8000, // visual variants
        0x0000_0000_FFF0_0000, // elevation
        0x0000_01FF_0000_0000, // fluid volume
        0x0000_1E00_0000_0000, // granular volume
        0x003F_E000_0000_0000, // surface state
        0x0FC0_0000_0000_0000, // terrain state
        0xF000_0000_0000_0000, // compass flags
        u64::MAX,
        0x0000_0000_FFFF_FFFF, // low word only
        0xFFFF_FFFF_0000_0000, // high word only
    ];
    for (cell, word) in cells.iter_mut().skip(1).zip(field_maxima) {
        *cell = WorldCell(word);
    }
    // SplitMix64 fills the rest with varied words that no generator rule would produce.
    let mut state: u64 = 0x1234_5678_9ABC_DEF0;
    for cell in cells.iter_mut().skip(1 + field_maxima.len()) {
        state = state.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = state;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        *cell = WorldCell(z ^ (z >> 31));
    }
    CellChunk {
        cells: cells.into_boxed_slice(),
        metadata: ChunkMetadata {
            last_simulated: 1234.5,
            theme: ChunkTheme::MOUNTAIN,
        },
    }
}

fn row_file_name(key: ChunkKey) -> String {
    format!("{}_{}_{}.bitcode", key.key.x, key.key.y, key.key.z)
}

fn append_row(manifest: &mut String, row: &FixtureRow, file: &str, byte_len: usize) {
    let cells = &row.chunk.cells;
    let sum = |field: fn(&WorldCell) -> u64| cells.iter().map(field).sum::<u64>();
    let words = |range: std::ops::Range<usize>| {
        cells[range]
            .iter()
            .map(|cell| format!("\"0x{:016X}\"", cell.0))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let last = cells.len();
    let _ = write!(
        manifest,
        "\n[[row]]\nkey = [{}, {}, {}]\nfile = \"rows/{file}\"\ndescription = \"{}\"\n\
         encoded_bytes = {byte_len}\ncells = {}\nlast_simulated = {:?}\ntheme = {}\n\
         elevation_sum = {}\nfluid_volume_sum = {}\ngranular_volume_sum = {}\n\
         surface_state_sum = {}\nfirst_words = [{}]\nlast_words = [{}]\n",
        row.key.key.x,
        row.key.key.y,
        row.key.key.z,
        row.description,
        cells.len(),
        row.chunk.metadata.last_simulated,
        row.chunk.metadata.theme.0,
        sum(|c| c.elevation() as u64),
        sum(|c| c.fluid_vol() as u64),
        sum(|c| c.granular_vol() as u64),
        sum(|c| c.surface_state() as u64),
        words(0..16),
        words(last - 4..last),
    );
}
